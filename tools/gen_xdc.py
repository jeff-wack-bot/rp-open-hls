#!/usr/bin/env python3
"""Derive a nextpnr-xilinx XDC for rp_top from the Red Pitaya vendor pin file
(redpitaya-fpga/sdc/red_pitaya.xdc, STEMlab 125-14).

nextpnr accepts only set_property (PACKAGE_PIN/IOSTANDARD/SLEW/DRIVE/...) and
create_clock on ports/nets; false paths and input delays are dropped.
Vendor port names are 2-D (adc_dat_i[ch][bit], adc_clk_i[1:0]); rp_top uses
the flat PyRPL names (adc_dat_a_i[bit], adc_clk_p_i/n_i).

usage: gen_xdc.py <vendor red_pitaya.xdc> > constraints/rp_125_14.xdc
"""
import re
import sys

src = open(sys.argv[1]).read()
pins = {}
for line in src.splitlines():
    m = re.match(r"\s*set_property\s+PACKAGE_PIN\s+(\S+)\s+\[get_ports\s+(.*)\]\s*$", line)
    if m:
        pins[m.group(2).strip().strip("{}").strip()] = m.group(1)

out = ["# Generated by tools/gen_xdc.py from the vendor red_pitaya.xdc (STEMlab 125-14)", ""]


def port(name, pin, std, extra=""):
    out.append(f"set_property -dict {{PACKAGE_PIN {pin} IOSTANDARD {std}{extra}}} [get_ports {{{name}}}]")


out.append("# ADC data, 14 bit on [15:2] (LVCMOS18, bank 34/35)")
for ch, name in ((0, "adc_dat_a_i"), (1, "adc_dat_b_i")):
    for b in range(2, 16):
        port(f"{name}[{b}]", pins[f"adc_dat_i[{ch}][{b}]"], "LVCMOS18")
out.append("# ADC clock (differential, vendor: adc_clk_i[1]=P, adc_clk_i[0]=N)")
port("adc_clk_p_i", pins["adc_clk_i[1]"], "DIFF_HSTL_I_18")
port("adc_clk_n_i", pins["adc_clk_i[0]"], "DIFF_HSTL_I_18")
for i in range(2):
    port(f"adc_clk_o[{i}]", pins[f"adc_clk_o[{i}]"], "LVCMOS18", " SLEW FAST DRIVE 8")
port("adc_cdcs_o", pins["adc_cdcs_o"], "LVCMOS18", " SLEW FAST DRIVE 8")
out.append("# DAC (LVCMOS33)")
for b in range(14):
    port(f"dac_dat_o[{b}]", pins[f"dac_dat_o[{b}]"], "LVCMOS33", " SLEW SLOW DRIVE 8")
for s in ("dac_wrt_o", "dac_sel_o", "dac_clk_o", "dac_rst_o"):
    port(s, pins[s], "LVCMOS33", " SLEW FAST DRIVE 8")
out.append("# LEDs")
for i in range(8):
    port(f"led_o[{i}]", pins[f"led_o[{i}]"], "LVCMOS33", " SLEW SLOW DRIVE 4")
out.append("")
out.append("# 125 MHz ADC clock (vendor: create_clock -period 8.000 [get_ports adc_clk_i[1]])")
out.append("create_clock -period 8.000 [get_ports adc_clk_p_i]")
print("\n".join(out))
